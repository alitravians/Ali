		for _, n in ipairs({ "Workspace", "ReplicatedStorage", "StarterGui", "Lighting", "SoundService" }) do
			local svc = game:FindFirstChild(n) or game:GetService(n)
			if svc then table.insert(list, svc) end
		end
	end
	return list
end

local startTime = os.clock()
