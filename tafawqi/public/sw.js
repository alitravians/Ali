// F9 — Tiny service worker. Caches the shell so the site keeps loading when
// offline and serves a tiny offline page from the cache. We deliberately
// avoid caching API responses; learners always see fresh data when online.
const CACHE = "tafawqi-shell-v1";
const SHELL = ["/", "/offline", "/icon.svg", "/manifest.webmanifest"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) => Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);

  // Never cache APIs or admin pages — must always be fresh and same-origin.
  if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/admin")) return;

  // Network-first for HTML navigation so updates roll out instantly online.
  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => undefined);
          return res;
        })
        .catch(() => caches.match(req).then((r) => r || caches.match("/offline"))),
    );
    return;
  }

  // Cache-first for static assets (CSS, JS, fonts, SVG).
  event.respondWith(
    caches.match(req).then((cached) => {
      if (cached) return cached;
      return fetch(req)
        .then((res) => {
          if (!res || res.status !== 200 || res.type !== "basic") return res;
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => undefined);
          return res;
        })
        .catch(() => cached as Response);
    }),
  );
});
